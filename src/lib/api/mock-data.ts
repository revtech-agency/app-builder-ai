const doneTurn = (
  id: string,
  minutesAgo: number,
  labels: string[],
  outcome: Turn["outcome"],
  cost: number,
  preview: string | null,
): Turn => ({
  id,
  status: outcome === "failed" ? "failed" : "completed",
  steps: labels.map((label, i) => ({
    label,
    status: outcome === "failed" && i === labels.length - 1 ? "failed" : "done",
  })),
  outcome,
  preview_url: preview,
  cost_usd: cost,
  started_at: ago(minutesAgo),
  ended_at: ago(minutesAgo - 1),
});

